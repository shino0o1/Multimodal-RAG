def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--coverage",
        default="dataset/build_dataset/curated/coverage_matrix.csv",
        help="Coverage matrix generated by curate_existing_dataset.py.",
    )
    parser.add_argument(
        "--output-dir",
        default="dataset/build_dataset/gaps",
        help="Output directory for gap target CSV and query JSONL.",
    )
    parser.add_argument("--min-count", type=int, default=5)
    parser.add_argument("--top-n", type=int, default=120)
    return parser.parse_args()


def read_coverage(path: Path) -> dict[tuple[str, str, str], int]:
    coverage: dict[tuple[str, str, str], int] = {}
    if not path.exists():
        return coverage
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            key = (
                str(row.get("crop", "")).strip(),
                str(row.get("target", "")).strip(),
                str(row.get("task_type", "")).strip(),
            )
            try:
                coverage[key] = int(row.get("count") or 0)
            except ValueError:
                coverage[key] = 0
    return coverage


def gap_level(count: int, min_count: int) -> str:
    if count == 0:
        return "empty"
    if count < min_count:
        return "thin"
    return "covered"


def build_rows(coverage: dict[tuple[str, str, str], int], min_count: int) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for crop in PRIMARY_CROPS:
        for target in COMMON_TARGETS:
            for task_type in TASK_TYPES:
                count = coverage.get((crop, target, task_type), 0)
                level = gap_level(count, min_count)
                if level == "covered":
                    continue
                rows.append(
                    {
                        "crop": crop,
                        "target": target,
                        "task_type": task_type,
                        "current_count": count,
                        "min_count": min_count,
                        "gap_level": level,
                        "priority_score": priority_score(crop, target, task_type, count),
                        "query": build_query(crop, target, task_type),
                    }
                )
    return sorted(rows, key=lambda row: (-row["priority_score"], row["crop"], row["target"], row["task_type"]))


def priority_score(crop: str, target: str, task_type: str, count: int) -> int:
    gap_bonus = 40 if count == 0 else 20
    return (
        CROP_PRIORITY.get(crop, 50)
        + TARGET_PRIORITY.get(target, 50)
        + TASK_PRIORITY.get(task_type, 50)
        + gap_bonus
        - count * 5
    )


def build_query(crop: str, target: str, task_type: str) -> str:
    hint = TASK_QUERY_HINTS.get(task_type, "")
    return f"{crop} {target} {hint} {PREFERRED_SOURCE_HINT}".strip()


def write_gap_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "crop",
        "target",
        "task_type",
        "current_count",
        "min_count",
        "gap_level",
        "priority_score",
        "query",
    ]
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_query_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for index, row in enumerate(rows, start=1):
            payload = {
                "id": f"gap-{index:04d}",
                "crop": row["crop"],
                "target": row["target"],
                "task_type": row["task_type"],
                "query": row["query"],
                "priority_score": row["priority_score"],
                "source_policy": "prefer_authoritative_sources",
            }
            handle.write(json.dumps(payload, ensure_ascii=False) + "\n")


def main() -> None:
    args = parse_args()
    output_dir = Path(args.output_dir)
    coverage = read_coverage(Path(args.coverage))
    rows = build_rows(coverage, args.min_count)
    priority_rows = rows[: max(0, args.top_n)]
    write_gap_csv(output_dir / "gap_targets.csv", rows)
    write_query_jsonl(output_dir / "search_queries.jsonl", rows)
    write_gap_csv(output_dir / f"priority_gap_targets_top{args.top_n}.csv", priority_rows)
    write_query_jsonl(output_dir / f"priority_search_queries_top{args.top_n}.jsonl", priority_rows)

    summary = {
        "coverage": args.coverage,
        "min_count": args.min_count,
        "top_n": args.top_n,
        "gap_targets": len(rows),
        "priority_targets": len(priority_rows),
        "empty": sum(1 for row in rows if row["gap_level"] == "empty"),
        "thin": sum(1 for row in rows if row["gap_level"] == "thin"),
        "output_dir": str(output_dir),
    }
    (output_dir / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
